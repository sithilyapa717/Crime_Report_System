// Document catalogue (D11): the reference staff and administrators use. Bilingual headings;
// generated from the registry, the field mapping and the template inventory so it never drifts.
//
// Usage: node packages/documents/scripts/catalogue.ts
// Writes: docs/document-catalogue/CATALOGUE.md
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { FIELDS, type FieldKind } from '../mapping/fields.ts';
import { FAMILY_ORDER, FAMILY_TITLES } from '../registry/families.ts';
import { JsonTemplateSource, OFFENCE_SPECIFIC, type TemplateEntry } from '../registry/registry.ts';

const REPO = join(import.meta.dirname, '..', '..', '..');
const OUT = join(REPO, 'docs', 'document-catalogue', 'CATALOGUE.md');
const INVENTORY = join(import.meta.dirname, '..', 'registry', 'template-inventory.json');

const inventory = (JSON.parse(readFileSync(INVENTORY, 'utf8')) as { templates: { path: string; mergeFields: string[]; fonts: string[] }[] })
  .templates;
const fieldsOf = new Map(inventory.map((t) => [t.path, t.mergeFields]));
const entries = await new JsonTemplateSource().list();
const cell = (s: string) => s.replace(/\|/g, '\\|');

const STATUS = { current: 'current – භාවිතයේ ඇත', unconfirmed: 'unconfirmed – තහවුරු කර නැත', archived: 'archived – පැරණි පිටපත' };
const FORMAT: Record<FieldKind, string> = {
  text: 'as entered',
  date: 'YYYY.MM.DD',
  time: 'HH.MM (to confirm)',
  number: 'plain number',
  money: 'rupees, no separators (to confirm)',
};

function variant(e: TemplateEntry): string {
  const v = e.variant;
  return [
    v.container === 'can' ? 'can / කෑන' : v.container === 'bottle' ? 'bottle / බෝතල' : '',
    v.sample === true ? 'sample / සාම්පල්' : v.sample === false ? 'no sample / සාම්පල් නැත' : '',
    v.volumeMl ? `${v.volumeMl} ml` : '',
    v.noteRs ? `Rs ${v.noteRs}` : '',
    v.offences ? `${v.offences} offences` : '',
  ]
    .filter(Boolean)
    .join(', ');
}

let md = `# Document catalogue – ලේඛන නාමාවලිය

Generated by \`packages/documents/scripts/catalogue.ts\` from the template registry, the field mapping and the
template inventory. **Do not edit by hand**: change \`registry/templates.json\` or \`mapping/fields.ts\` and run the script.

*Sinhala headings are working text for staff review (they are not app captions).*

- ${entries.length} templates (the original Word files, never changed by the app)
- ${entries.filter((e) => e.status === 'current').length} current, ${entries.filter((e) => e.status === 'unconfirmed').length} not yet confirmed by staff, ${entries.filter((e) => e.status === 'archived').length} archived
- ${FIELDS.length} data fields filled in by the app

## How the app uses the templates – යෙදුම ආකෘති භාවිතා කරන ආකාරය

1. The user opens a CR and chooses **ලේඛන සාදන්න** (generate documents).
2. The app offers the templates for that CR's offence, plus the general ones (vouchers, motion sheets, …). Archived
   templates are never offered; plaints without an offence code are not offered until one is set.
3. The app copies the chosen original, fills only the merge fields with the CR's data, and saves the copy as
   \`CR <number> - <template name>.docx\`. The wording of the document is never changed.
4. A second document from the same template is saved as \`… (2).docx\`; nothing is overwritten. Every document made is
   logged: who, when, which template version.

## Templates by family – ආකෘති වර්ග අනුව

`;

for (const family of FAMILY_ORDER) {
  const rows = entries.filter((e) => e.family === family).sort((a, b) => a.offenceCodes.join().localeCompare(b.offenceCodes.join()) || a.id.localeCompare(b.id));
  if (!rows.length) continue;
  md += `### ${FAMILY_TITLES[family].en} – ${FAMILY_TITLES[family].si}\n\n`;
  md += `| Template – ආකෘතිය | Offence – වරද | Variant – වර්ගය | Fields | Status – තත්ත්වය |\n|---|---|---|---|---|\n`;
  for (const e of rows) {
    const offence = e.offenceCodes.join(' ') || (OFFENCE_SPECIFIC.includes(family) ? '**not set – not offered**' : 'any');
    md += `| ${cell(e.id)} | ${offence} | ${variant(e)} | ${(fieldsOf.get(e.id) ?? []).length} | ${STATUS[e.status]} |\n`;
  }
  md += '\n';
}

md += `## Data fields – දත්ත ක්ෂේත්‍ර

Each template marks the places to fill with Word merge fields. The app fills them from the CR record. Field names
are matched ignoring case; the other names are older spellings found in some templates.

| Field | Other names in templates | Meaning | Printed as | Used by |
|---|---|---|---|---|
`;
const usedBy = (names: string[]) =>
  inventory.filter((t) => t.mergeFields.some((f) => names.some((n) => n.toLowerCase() === f.toLowerCase()))).length;
for (const f of FIELDS) {
  const names = [f.name, ...(f.aliases ?? []).map((a) => a.name)];
  const aliases = (f.aliases ?? []).map((a) => `\`${a.name}\`${a.confirmed ? '' : ' (to confirm)'}`).join(', ');
  md += `| \`${f.name}\` | ${aliases} | ${cell(f.label)} | ${FORMAT[f.kind]} | ${usedBy(names)} |\n`;
}

const fontUse = new Map<string, number>();
for (const t of inventory) for (const f of t.fonts) fontUse.set(f, (fontUse.get(f) ?? 0) + 1);
md += `
## Fonts used by the templates – අකුරු වර්ග

Install these on every PC that prints documents. \`node packages/documents/scripts/check-fonts.ts\` lists the ones
missing on a PC. See docs/admin-guide/DOCUMENTS_ADMIN.md.

| Font | Templates |
|---|---|
${[...fontUse]
  .sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0]))
  .map(([f, n]) => `| ${cell(f)} | ${n} |`)
  .join('\n')}

## Adding or replacing a template – ආකෘතියක් එක් කිරීම හෝ වෙනස් කිරීම

An original is **never edited or overwritten**: earlier documents must stay traceable to the exact file used.
A changed template is added as a new file and the old one is archived.

1. Get the new \`.docx\` from staff, with its offence code(s), and confirm it is the version to use.
2. Add it with a new file name:
   \`\`\`
   node packages/documents/scripts/add-template.ts "<new.docx>" "PUDS/puds බෝතලය 2027.docx" --offence PUDS --replaces "PUDS/puds  බෝතලය.docx" --current
   \`\`\`
   The tool refuses files that are not Word documents, names that already exist, and templates that use a merge
   field the app does not know (add the field to \`packages/documents/mapping/fields.ts\` first).
3. Approve the new wording snapshot and refresh the generated lists:
   \`\`\`
   node tests/documents-fidelity/approve-fixed-text.ts
   node packages/documents/scripts/inventory-templates.ts
   node packages/documents/scripts/family-audit.ts
   node packages/documents/scripts/catalogue.ts
   \`\`\`
4. Run the tests: \`node --test "packages/documents/**/*.test.ts" "tests/documents-fidelity/*.test.ts"\`.
5. Open a pull request. Check the wording diff in \`tests/documents-fidelity/fixed-text/\`. The template folder is
   read-only in CI, so the project owner adds the \`read-only-change\` label after checking the new file.

To only mark templates current or archived (no new file), use the staff review sheet:
\`review-pack.ts\` → staff fill \`review-sheet.csv\` → \`apply-review.ts\`.

## Related files

- \`docs/document-catalogue/TEMPLATE_INVENTORY.md\` – every template with its merge fields, data source query and fonts
- \`docs/document-catalogue/MERGE_FIELDS.md\` – every merge field and where it is used
- \`docs/document-catalogue/FAMILIES.md\` – family audit, including which fields the data service supplies
- \`docs/engine-notes/WORD_COMPARISON.md\` – engine output compared with Word's own mail merge
`;

writeFileSync(OUT, md, 'utf8');
console.log(`Wrote ${OUT}`);
