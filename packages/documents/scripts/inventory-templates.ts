// Phase 1: inventory of the frozen originals (read-only).
// For each template: merge fields, other field codes, the Access mail-merge query, fonts.
//
// Usage: node packages/documents/scripts/inventory-templates.ts
// Writes:
//   packages/documents/registry/template-inventory.json   (machine-readable, for the registry)
//   docs/document-catalogue/TEMPLATE_INVENTORY.md         (draft catalogue for staff to mark "current")
//   docs/document-catalogue/MERGE_FIELDS.md               (field union = B8 data contract input)
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { decodeXmlEntities, fieldInstructions, mergeFieldName, readZipEntries } from './docx-read.ts';
import { MANIFEST_PATH, ORIGINALS_DIR, type Manifest } from './originals-lib.ts';

const REPO = join(import.meta.dirname, '..', '..', '..');
const INVENTORY_JSON = join(REPO, 'packages', 'documents', 'registry', 'template-inventory.json');
const INVENTORY_MD = join(REPO, 'docs', 'document-catalogue', 'TEMPLATE_INVENTORY.md');
const FIELDS_MD = join(REPO, 'docs', 'document-catalogue', 'MERGE_FIELDS.md');

interface TemplateInfo {
  path: string;
  folder: string;
  sha256: string;
  mergeFields: string[]; // unique, in first-use order
  mergeFieldUses: number;
  fieldsInHeadersFooters: string[];
  otherFieldCodes: string[]; // e.g. IF, NEXT, PAGE: unique keywords
  mailMergeQuery: string | null;
  hasDataSourceLink: boolean;
  fonts: string[];
  sameBytesAs: string[];
  error?: string;
}

const manifest = JSON.parse(readFileSync(MANIFEST_PATH, 'utf8')) as Manifest;
const templates: TemplateInfo[] = [];

for (const entry of manifest.files) {
  const folder = entry.path.includes('/') ? entry.path.split('/')[0] : '(root)';
  const info: TemplateInfo = {
    path: entry.path,
    folder,
    sha256: entry.sha256,
    mergeFields: [],
    mergeFieldUses: 0,
    fieldsInHeadersFooters: [],
    otherFieldCodes: [],
    mailMergeQuery: null,
    hasDataSourceLink: false,
    fonts: [],
    sameBytesAs: [],
  };
  try {
    const zip = readZipEntries(join(ORIGINALS_DIR, entry.path));
    const text = (name: string) => zip.get(name)?.toString('utf8') ?? '';
    const parts = [...zip.keys()].filter((n) =>
      /^word\/(document|header\d*|footer\d*|footnotes|endnotes)\.xml$/.test(n),
    );
    const fields = new Set<string>();
    const hf = new Set<string>();
    const other = new Set<string>();
    for (const part of parts) {
      for (const instr of fieldInstructions(text(part))) {
        const name = mergeFieldName(instr);
        if (name) {
          fields.add(name);
          info.mergeFieldUses++;
          if (/header|footer/.test(part)) hf.add(name);
        } else {
          const kw = instr.split(/\s+/)[0]?.toUpperCase();
          if (kw) other.add(kw);
        }
      }
    }
    info.mergeFields = [...fields];
    info.fieldsInHeadersFooters = [...hf];
    info.otherFieldCodes = [...other].sort();

    const settings = text('word/settings.xml');
    const q = /<w:mailMerge\b[\s\S]*?<w:query\b[^>]*\bw:val="([^"]*)"/.exec(settings);
    info.mailMergeQuery = q ? decodeXmlEntities(q[1]) : null;
    info.hasDataSourceLink = /<w:mailMerge\b[\s\S]*?<w:dataSource\b/.test(settings);

    const fonts = new Set<string>();
    for (const part of [...parts, 'word/styles.xml']) {
      for (const m of text(part).matchAll(/<w:rFonts\b([^>]*)\/?>/g)) {
        for (const a of m[1].matchAll(/w:(?:ascii|hAnsi|cs|eastAsia)="([^"]+)"/g)) fonts.add(a[1]);
      }
    }
    info.fonts = [...fonts].sort();
  } catch (e) {
    info.error = (e as Error).message;
  }
  templates.push(info);
}

const byHash = new Map<string, string[]>();
for (const t of templates) byHash.set(t.sha256, [...(byHash.get(t.sha256) ?? []), t.path]);
for (const t of templates) t.sameBytesAs = (byHash.get(t.sha256) ?? []).filter((p) => p !== t.path);

// ---- outputs ----------------------------------------------------------------------------
writeFileSync(
  INVENTORY_JSON,
  JSON.stringify({ generatedFrom: 'templates/original/MANIFEST.json', templates }, null, 2) + '\n',
  'utf8',
);

const cell = (s: string) => s.replace(/\|/g, '\\|').replace(/\n/g, ' ');
const looksLikeCopy = (p: string) => /( 1{1,3}| \d)\.docx$|\.docx \d|111|1111/i.test(p);

const folders = [...new Set(templates.map((t) => t.folder))];
let md = `# Template inventory (draft)

Generated by \`packages/documents/scripts/inventory-templates.ts\` from the ${templates.length} frozen originals. **Do not edit by hand.** Re-run the script instead. Staff decisions go in the "Current?" column of the copy that is sent for review.

- **Copy?** marks file names that look like saved-again copies (\`… 1.docx\`, \`… 11.docx\`, \`111\`). It's a hint for staff, not a decision.
- **Query** is the Access mail-merge filter stored in the file, removed only in generated copies.

`;
for (const folder of folders) {
  const rows = templates.filter((t) => t.folder === folder);
  md += `## ${folder}\n\n| File | Merge fields | Uses | Other field codes | Query | Fonts | Copy? | Current? |\n|---|---|---|---|---|---|---|---|\n`;
  for (const t of rows) {
    const file = t.path.slice(folder === '(root)' ? 0 : folder.length + 1);
    const notes = [looksLikeCopy(t.path) ? 'maybe' : '', t.sameBytesAs.length ? `identical to ${t.sameBytesAs.join(', ')}` : '']
      .filter(Boolean)
      .join('; ');
    md += `| ${cell(file)} | ${t.error ? `**ERROR: ${cell(t.error)}**` : t.mergeFields.length} | ${t.mergeFieldUses} | ${cell(t.otherFieldCodes.join(', '))} | ${cell(t.mailMergeQuery ?? '')} | ${cell(t.fonts.join(', '))} | ${cell(notes)} |  |\n`;
  }
  md += '\n';
}
writeFileSync(INVENTORY_MD, md, 'utf8');

const usage = new Map<string, { templates: number; folders: Set<string>; inHeaderFooter: boolean }>();
for (const t of templates) {
  for (const f of t.mergeFields) {
    const u = usage.get(f) ?? { templates: 0, folders: new Set<string>(), inHeaderFooter: false };
    u.templates++;
    u.folders.add(t.folder);
    if (t.fieldsInHeadersFooters.includes(f)) u.inHeaderFooter = true;
    usage.set(f, u);
  }
}
const fieldRows = [...usage.entries()].sort((a, b) => b[1].templates - a[1].templates || a[0].localeCompare(b[0]));
let fmd = `# Merge fields used by the original templates

Generated by \`packages/documents/scripts/inventory-templates.ts\`. **Do not edit by hand.**

This is the full list of fields that the document-data service (B8) must provide. "Meaning", "Source in new schema" and "Format" are filled in with B during Phase 1 (D2) in \`packages/documents/mapping/\`, not here.

${usage.size} distinct fields across ${templates.length} templates.

| Field | Templates | Folders | In header/footer |
|---|---|---|---|
`;
for (const [name, u] of fieldRows) {
  fmd += `| \`${cell(name)}\` | ${u.templates} | ${cell([...u.folders].join(', '))} | ${u.inHeaderFooter ? 'yes' : ''} |\n`;
}
writeFileSync(FIELDS_MD, fmd, 'utf8');

const errors = templates.filter((t) => t.error);
console.log(`Inventoried ${templates.length} templates, ${usage.size} distinct merge fields, ${errors.length} errors.`);
for (const t of errors) console.log(`  ERROR ${t.path}: ${t.error}`);
