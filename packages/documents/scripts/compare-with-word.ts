// Compares the engine with Word's own mail merge (Windows only, needs Microsoft Word).
// For each template that has merge fields:
//   1. fill it with the engine, using marker values (each text field gets its own ⟦marker⟧);
//   2. let Word merge the same values into a copy of the original (Access link removed);
//   3. compare the visible text of both results.
// Writes docs/engine-notes/WORD_COMPARISON.md.
//
// Usage: node packages/documents/scripts/compare-with-word.ts <work dir> [path filter]
import { spawnSync } from 'node:child_process';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { fillTemplate, removeMailMergeLink, type DocumentData } from '../engine/fill.ts';
import { DocxZip } from '../engine/zip.ts';
import { FIELDS, formatValue, lookupField } from '../mapping/fields.ts';
import { plainText } from '../../../tests/documents-fidelity/fidelity-lib.ts';
import { MANIFEST_PATH, ORIGINALS_DIR, type Manifest } from './originals-lib.ts';

const REPO = join(import.meta.dirname, '..', '..', '..');
const REPORT = join(REPO, 'docs', 'engine-notes', 'WORD_COMPARISON.md');
const [workArg, filter] = process.argv.slice(2);
if (!workArg) {
  console.error('Usage: node compare-with-word.ts <work dir> [path filter]');
  process.exit(2);
}
const work = resolve(workArg);
mkdirSync(work, { recursive: true });

const DATA: DocumentData = {};
for (const f of FIELDS) {
  DATA[f.name] =
    f.kind === 'date' ? '2026-01-02' : f.kind === 'time' ? '01:02' : f.kind === 'money' ? 123400 : `⟦${f.name}⟧`;
}

interface Job {
  path: string;
  template: string;
  dataSource: string;
  values: { name: string; value: string }[];
  out: string;
  engineOut: Buffer;
}

const manifest = JSON.parse(readFileSync(MANIFEST_PATH, 'utf8')) as Manifest;
const jobs: Job[] = [];
manifest.files
  .filter((f) => !filter || f.path.includes(filter))
  .forEach((f, i) => {
    const original = readFileSync(join(ORIGINALS_DIR, f.path));
    const { docx, report } = fillTemplate(original, DATA);
    if (!report.templateFields.length) return;
    // Word matches merge-field names to data-source columns ignoring case: one column per name
    const values: { name: string; value: string }[] = [];
    for (const name of report.templateFields) {
      if (values.some((v) => v.name.toLowerCase() === name.toLowerCase())) continue;
      const def = lookupField(name);
      values.push({ name, value: def ? (formatValue(def, DATA[def.name]) ?? '') : '' });
    }
    const unlinked = DocxZip.read(original);
    removeMailMergeLink(unlinked);
    const template = join(work, `t${i}.docx`);
    writeFileSync(template, unlinked.write());
    jobs.push({
      path: f.path,
      template,
      dataSource: join(work, `d${i}.docx`),
      values,
      out: join(work, `w${i}.docx`),
      engineOut: docx,
    });
  });

const jobsFile = join(work, 'jobs.json');
writeFileSync(
  jobsFile,
  JSON.stringify(jobs.map((j) => ({ template: j.template, dataSource: j.dataSource, values: j.values, out: j.out }))),
  'utf8',
);
console.log(`Word is merging ${jobs.length} templates…`);
const ps = spawnSync(
  'powershell.exe',
  ['-NoProfile', '-ExecutionPolicy', 'Bypass', '-File', join(import.meta.dirname, 'word-merge.ps1'), jobsFile],
  { encoding: 'utf8', timeout: 30 * 60 * 1000 },
);
const wordLog = new Map<string, string>();
for (const line of (ps.stdout ?? '').split(/\r?\n/)) {
  const m = /^(ok|FAIL)\s+(.+?)(?::\s(.*))?$/.exec(line.trim());
  if (m) wordLog.set(resolve(m[2]!), m[1] === 'ok' ? 'ok' : (m[3] ?? 'failed'));
}

// Word ends a merged document with a section break paragraph; trailing blank lines are not wording.
const norm = (s: string) => s.replace(/\s+$/, '');

const rows: string[] = [];
let same = 0;
for (const job of jobs) {
  const status = wordLog.get(resolve(job.template));
  if (status !== 'ok') {
    rows.push(`| ${job.path} | Word merge failed: ${status ?? 'no result'} |`);
    continue;
  }
  const word = norm(plainText(DocxZip.read(readFileSync(job.out)).getText('word/document.xml') ?? ''));
  const engine = norm(plainText(DocxZip.read(job.engineOut).getText('word/document.xml') ?? ''));
  if (word === engine) {
    same++;
    rows.push(`| ${job.path} | identical |`);
  } else {
    let i = 0;
    while (word[i] === engine[i]) i++;
    const ctx = (s: string) => JSON.stringify(s.slice(Math.max(0, i - 30), i + 40)).replace(/\|/g, '\\|');
    rows.push(`| ${job.path} | **differs** at char ${i}: Word ${ctx(word)} vs engine ${ctx(engine)} |`);
  }
}

writeFileSync(
  REPORT,
  `# Engine vs Word mail merge

Generated by \`packages/documents/scripts/compare-with-word.ts\` (needs Windows + Word, not run in CI).
Each template with merge fields was filled twice with the same marker values: once by the engine,
once by Word's own mail merge. The visible text of the main document is compared.

**${same} of ${jobs.length} identical.**

| Template | Result |
|---|---|
${rows.join('\n')}
`,
  'utf8',
);
console.log(`${same}/${jobs.length} identical. Report: ${REPORT}`);
if (ps.status !== 0) console.error(ps.stderr);
process.exit(same === jobs.length ? 0 : 1);
