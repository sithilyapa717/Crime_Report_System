// Phase 5 (D8): audit of every document family.
// For each family: its templates, offences, variants, the fields it needs, and whether the
// document-data service (B8, packages/services/docdata) produces each field.
//
// B's field list is read from its source text (report only: packages/documents is not a pnpm
// workspace package yet, so it cannot import @excise/docdata).
//
// Usage: node packages/documents/scripts/family-audit.ts
// Writes: docs/document-catalogue/FAMILIES.md
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { lookupField } from '../mapping/fields.ts';
import { JsonTemplateSource, OFFENCE_SPECIFIC, type TemplateEntry, type TemplateFamily } from '../registry/registry.ts';

const REPO = join(import.meta.dirname, '..', '..', '..');
const OUT = join(REPO, 'docs', 'document-catalogue', 'FAMILIES.md');
const B8 = join(REPO, 'packages', 'services', 'docdata', 'src', 'index.ts');
const INVENTORY = join(import.meta.dirname, '..', 'registry', 'template-inventory.json');

const FAMILY_NAMES: Record<TemplateFamily, string> = {
  plaint: 'Plaints by offence (පැමිණිලි)',
  'charge-sheet': 'Charge sheets (චෝදනා පත්‍ර)',
  'reward-voucher': 'Reward and fine vouchers (REWARDS, ඊ 6c)',
  'motion-sheet': 'Motion sheets (මෝෂන් කොළ)',
  'warrant-extension': 'Warrant extension (වරෙන්තු දිර්ග කිරීම)',
  'previous-record': 'Previous-record notes (පෙර වැරදි)',
  production: 'Productions (සාක්ෂි භාණ්ඩ)',
  other: 'Other',
};

/** Field names B8 returns, read from buildFields() in its source; null if the file is missing. */
function b8Fields(): { produced: Set<string>; unresolved: Set<string> } | null {
  if (!existsSync(B8)) return null;
  const src = readFileSync(B8, 'utf8');
  const body = src.slice(src.indexOf('export function buildFields'));
  const produced = new Set<string>();
  for (const m of body.matchAll(/^\s+'?([\w඀-෿]+)'?:\s/gm)) produced.add(m[1]!);
  if (/fields\[`dh\$\{/.test(body)) for (let i = 1; i <= 5; i++) produced.add(`dh${i}`);
  if (/fields\[`inh\$\{/.test(body)) for (let i = 1; i <= 5; i++) produced.add(`inh${i}`);
  const unresolvedList = /UNRESOLVED_FIELDS\s*=\s*\[([^\]]*)\]/.exec(src)?.[1] ?? '';
  const unresolved = new Set([...unresolvedList.matchAll(/'([^']+)'/g)].map((m) => m[1]!));
  unresolved.forEach((u) => produced.add(u));
  return { produced, unresolved };
}

const entries = await new JsonTemplateSource().list();
const inventory = new Map(
  (JSON.parse(readFileSync(INVENTORY, 'utf8')) as { templates: { path: string; mergeFields: string[] }[] }).templates.map(
    (t) => [t.path, t.mergeFields],
  ),
);
const b8 = b8Fields();
const cell = (s: string) => s.replace(/\|/g, '\\|');

function variantText(e: TemplateEntry): string {
  const v = e.variant;
  return [
    v.container === 'can' ? 'can' : v.container === 'bottle' ? 'bottle' : '',
    v.sample === true ? 'sample' : v.sample === false ? 'no sample' : '',
    v.volumeMl ? `${v.volumeMl} ml` : '',
    v.noteRs ? `Rs ${v.noteRs}` : '',
    v.offences ? `${v.offences} offences` : '',
  ]
    .filter(Boolean)
    .join(', ');
}

function coverage(fields: string[]): { missing: string[]; unresolved: string[] } {
  if (!b8) return { missing: [], unresolved: [] };
  const missing: string[] = [];
  const unresolved: string[] = [];
  for (const f of fields) {
    // B8 must produce the exact template name (it is keyed by merge-field name) or, failing that,
    // the canonical name or an alias the engine falls back to
    const def = lookupField(f);
    const names = [f, ...(def ? [def.name, ...(def.aliases ?? []).map((a) => a.name)] : [])];
    const hit = names.find((n) => [...b8.produced].some((p) => p.toLowerCase() === n.toLowerCase()));
    if (!hit) missing.push(f);
    else if ([...b8.unresolved].some((u) => u.toLowerCase() === hit.toLowerCase())) unresolved.push(f);
  }
  return { missing, unresolved };
}

let md = `# Document families (Phase 5 audit)

Generated by \`packages/documents/scripts/family-audit.ts\`. **Do not edit by hand.**
Sources: \`registry/templates.json\` (families, offences, variants, status), \`registry/template-inventory.json\`
(fields per template) and the field list in \`packages/services/docdata\` (B8)${b8 ? '' : ' (**not found**)'}.

- **Not supplied by B8:** the template uses the field, and the document-data service returns nothing for it, so it prints empty.
- **Unresolved:** B8 returns it empty on purpose until its meaning is agreed.

`;

const summary: string[] = [];
for (const family of Object.keys(FAMILY_NAMES) as TemplateFamily[]) {
  const rows = entries.filter((e) => e.family === family);
  if (!rows.length) continue;
  const fields = [...new Set(rows.flatMap((e) => inventory.get(e.id) ?? []))].sort((a, b) => a.localeCompare(b));
  const cov = coverage(fields);
  const offences = [...new Set(rows.flatMap((e) => e.offenceCodes))].sort();
  const noOffence = OFFENCE_SPECIFIC.includes(family) ? rows.filter((e) => !e.offenceCodes.length) : [];
  const staticCount = rows.filter((e) => !(inventory.get(e.id) ?? []).length).length;
  const status = (s: TemplateEntry['status']) => rows.filter((e) => e.status === s).length;
  summary.push(
    `| ${FAMILY_NAMES[family]} | ${rows.length} | ${status('current')} / ${status('unconfirmed')} / ${status('archived')} | ${fields.length} | ${cov.missing.length + cov.unresolved.length || '–'} | ${noOffence.length || '–'} |`,
  );

  md += `## ${FAMILY_NAMES[family]}\n\n`;
  md += `- ${rows.length} templates; offences: ${offences.length ? offences.join(', ') : 'any'}`;
  md += staticCount ? `; ${staticCount} without merge fields (printed as they are)\n` : '\n';
  md += `- ${fields.length} distinct fields: ${fields.map((f) => `\`${f}\``).join(', ') || '–'}\n`;
  if (cov.missing.length) md += `- **Not supplied by B8:** ${cov.missing.map((f) => `\`${f}\``).join(', ')}\n`;
  if (cov.unresolved.length) md += `- **Unresolved in B8:** ${cov.unresolved.map((f) => `\`${f}\``).join(', ')}\n`;
  if (noOffence.length) md += `- **No offence code yet, so not offered:** ${noOffence.map((e) => cell(e.title)).join('; ')}\n`;
  md += `\n| Template | Offences | Variant | Fields | Status | Notes |\n|---|---|---|---|---|---|\n`;
  for (const e of [...rows].sort((a, b) => a.id.localeCompare(b.id))) {
    md += `| ${cell(e.id)} | ${e.offenceCodes.join(', ') || 'any'} | ${variantText(e)} | ${(inventory.get(e.id) ?? []).length} | ${e.status} | ${cell(e.notes ?? '')} |\n`;
  }
  md += '\n';
}

md = md.replace(
  '\n## ',
  `\n## Summary\n\n| Family | Templates | Current / unconfirmed / archived | Fields | Data gaps | Plaints without offence |\n|---|---|---|---|---|---|\n${summary.join('\n')}\n\n## `,
);
writeFileSync(OUT, md, 'utf8');
console.log(`Wrote ${OUT}`);
