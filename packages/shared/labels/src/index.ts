/** Caption for a service error code, falling back to a general message. */
export function errorLabel(code: string | undefined): string {
  const key = `error.${code ?? 'unknown'}`;
  return key in LABELS ? label(key) : label('error.unknown');
}

/** The caption to show: Sinhala when known, otherwise English; unknown keys show the key. */
export function label(key: string): string {
  const entry = (LABELS as Record<string, Label>)[key];
  return entry ? (entry.si ?? entry.en) : key;
}
